BEGIN;
CREATE ROLE financeiro_app NOLOGIN;
GRANT authenticated TO financeiro_app;
CREATE ROLE financeiro_server NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
GRANT financeiro_app TO financeiro_server;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public,auth,storage,extensions TO financeiro_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO financeiro_app;
GRANT SELECT ON storage.objects TO financeiro_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO financeiro_app;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public,auth,storage FROM PUBLIC;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public,auth TO financeiro_app;
CREATE SCHEMA app_private;
CREATE TABLE app_private.sessions(token_hash text PRIMARY KEY,user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,expires_at timestamptz NOT NULL,created_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX sessions_expiry ON app_private.sessions(expires_at);
CREATE TABLE app_private.login_attempts(key text PRIMARY KEY,attempts integer NOT NULL,window_start timestamptz NOT NULL);
GRANT USAGE ON SCHEMA auth,app_private TO financeiro_server;
GRANT SELECT(id,email,encrypted_password,raw_user_meta_data,deleted_at,banned_until,email_confirmed_at) ON auth.users TO financeiro_server;
CREATE POLICY local_auth_backend ON auth.users FOR SELECT TO financeiro_server USING (true);
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA app_private TO financeiro_server;
COMMIT;
